name ="baibahv"

print(len(name)) #print the length of the string 'name'
print(name.endswith("v")) #check if the string 'name' ends with the letter 'v'
print(name.startswith("b")) #check if the string 'name' starts with the letter 'b'
print(name.capitalize()) #capitalize the first letter of the string 'name'
print(name.upper()) #convert the string 'name' to uppercase
print(name.lower()) #convert the string 'name' to lowercase
print(name.replace("b", "B")) #replace all occurrences of 'b' with 'B' in the string 'name'
print(name.find("v")) #find the index of the first occurrence of 'v' in the string 'name'
print(name.count("a")) #count the number of occurrences of 'a' in the string 'name'